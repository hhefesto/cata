-- adj/LazyGhc.hs: GHC's own laziness on a few programs of the fragment,
-- written as Bend equations (adj/LAZY.bend) that Bend's checker and
-- BendTT's kernel compute against Core.bend's lazy meaning (eval.lz): so
-- the model's laziness is GHC's, not one written to fit the proof.  Each
-- program is written twice, as the model's term and as the Haskell it
-- stands for (error "e" for HErr), and GHC's answer is observed part by
-- part: a part is None{} where forcing it throws, so a pair with an error
-- in it is a pair.  Run by adj/int.zsh; LAZY.bend is its output, not
-- edited by hand.
module Main (main) where

import Control.Exception (SomeException, evaluate, try)

-- a thunk's answer, an exception its None
class Obs a where
  whnf :: a -> IO String

obs :: Obs a => a -> IO String
obs x = do
  r <- try (evaluate x >>= whnf >>= \s -> length s `seq` pure s)
  pure (either (\e -> const "None{}" (e :: SomeException)) (\s -> "Some{" ++ s ++ "}") r)

instance Obs Integer where
  whnf n = pure ("C.LvNat{" ++ show n ++ "n}")

instance Obs Bool where
  whnf b = pure ("C.LvBool{" ++ (if b then "True" else "False") ++ "{}}")

instance Obs () where
  whnf () = pure "C.LvUnit{}"

instance (Obs a, Obs b) => Obs (a, b) where
  whnf (a, b) = do
    sa <- obs a
    sb <- obs b
    pure ("C.LvPair{" ++ sa ++ ", " ++ sb ++ "}")

instance (Obs a, Obs b) => Obs (Either a b) where
  whnf (Left a) = (\s -> "C.LvInl{" ++ s ++ "}") <$> obs a
  whnf (Right b) = (\s -> "C.LvInr{" ++ s ++ "}") <$> obs b

e :: a
e = error "e"

-- the model's foldr: s at (head, the fold of the tail)
fold :: (() -> r) -> ((h, r) -> r) -> [h] -> r
fold z s = go
  where
    go [] = z ()
    go (h : t) = s (h, go t)

-- the list [5, 6], as Core.bend's lz of it
l56 :: String
l56 = "C.LvCons{Some{C.LvNat{5n}}, Some{C.LvCons{Some{C.LvNat{6n}}, Some{C.LvNil{}}}}}"

-- (name, the model's term, its input (lz of a value with no error), GHC's answer)
tests :: [(String, String, String, IO String)]
tests =
  [ ("fstErr", "C.HComp{C.HFst{}, C.HPr{C.HLit{1n}, C.HErr{}}}", "C.LvUnit{}", obs ((\_ -> fst (1 :: Integer, e :: Integer)) ()))
  , ("sndErr", "C.HComp{C.HSnd{}, C.HPr{C.HErr{}, C.HLit{2n}}}", "C.LvUnit{}", obs ((\_ -> snd (e :: Integer, 2 :: Integer)) ()))
  , ("pairErr", "C.HPr{C.HErr{}, C.HLit{1n}}", "C.LvUnit{}", obs ((\_ -> (e :: Integer, 1 :: Integer)) ()))
  , ("leftErr", "C.HComp{C.HInl{}, C.HErr{}}", "C.LvUnit{}", obs ((\_ -> Left e :: Either Integer ()) ()))
  , ("caseLeftErr", "C.HComp{C.HCase{C.HLit{3n}, C.HLit{4n}}, C.HComp{C.HInl{}, C.HErr{}}}", "C.LvUnit{}", obs ((\_ -> either (const 3) (const 4) (Left (e :: Integer) :: Either Integer ()) :: Integer) ()))
  , ("ifErr", "C.HIf{C.HComp{C.HPrim{C.PLt{}}, C.HPr{C.HLit{0n}, C.HLit{1n}}}, C.HLit{1n}, C.HErr{}}", "C.LvUnit{}", obs ((\_ -> if (0 :: Integer) < 1 then 1 else e :: Integer) ()))
  , ("foldConst", "C.HFold{C.HErr{}, C.HLit{1n}}", l56, obs (fold (const e) (const 1) [5, 6 :: Integer] :: Integer))
  , ("foldSnd", "C.HFold{C.HLit{0n}, C.HSnd{}}", l56, obs (fold (const 0) snd [5, 6 :: Integer] :: Integer))
  , ("foldSum", "C.HFold{C.HLit{0n}, C.HComp{C.HPrim{C.PAdd{}}, C.HPr{C.HFst{}, C.HSnd{}}}}", l56, obs (fold (const 0) (uncurry (+)) [5, 6 :: Integer] :: Integer))
  , ("foldHead", "C.HFold{C.HErr{}, C.HFst{}}", l56, obs (fold (const e) fst [5, 6 :: Integer] :: Integer))
  , ("addErr", "C.HComp{C.HPrim{C.PAdd{}}, C.HPr{C.HLit{1n}, C.HErr{}}}", "C.LvUnit{}", obs ((\_ -> 1 + (e :: Integer)) ()))
  , ("fstOfErr", "C.HComp{C.HFst{}, C.HErr{}}", "C.LvUnit{}", obs ((\_ -> fst (e :: (Integer, Integer))) ()))
  , ("pairIdErr", "C.HPr{C.HId{}, C.HErr{}}", "C.LvNat{3n}", obs ((\x -> (x, e :: Integer)) (3 :: Integer)))
  , ("foldPairs", "C.HFold{C.HPr{C.HErr{}, C.HLit{0n}}, C.HPr{C.HFst{}, C.HComp{C.HSnd{}, C.HSnd{}}}}", l56, obs (fold (const (e :: Integer, 0 :: Integer)) (\(h, r) -> (h, snd r)) [5, 6 :: Integer]))
  ]

main :: IO ()
main = do
  putStrLn "# generated by adj/LazyGhc.hs (adj/int.zsh) from GHC; do not edit"
  putStrLn "# Each def: the model's lazy meaning (Core.bend's eval.lz) of a program"
  putStrLn "# at its input is GHC's answer for the Haskell it stands for, observed"
  putStrLn "# part by part (None{}: forcing that part throws)."
  putStrLn ""
  putStrLn "import Base"
  putStrLn "import ./Core.bend as C"
  mapM_ test tests
  where
    test (name, t, x, ghc) = do
      r <- ghc
      putStrLn ""
      putStrLn ("def ghc." ++ name ++ "() -> {C.eval.lz(" ++ t ++ ", Some{" ++ x ++ "}) == " ++ r ++ " : Maybe<&2, C.LV>}:")
      putStrLn "  {==}"
