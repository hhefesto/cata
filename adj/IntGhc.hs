-- adj/IntGhc.hs: GHC's own Int arithmetic on a grid (-4..4 squared),
-- and GHC's Int8 at its edges (minBound, maxBound and around them,
-- squared), written as Bend equations (adj/INT.bend) that Bend's checker
-- and BendTT's kernel compute against Core.bend's model of Int (z.prim,
-- every integer) and of Int's range (z.primw at RgInt{127n}, 8 bits:
-- (+) and (-) wrap around, div at minBound by -1 errs): so the model's
-- Int is GHC's, not one written to fit the proof.  Run by adj/int.zsh;
-- INT.bend is its output, not edited by hand.
module Main (main) where

import Control.Exception (ArithException, evaluate, try)
import Data.Int (Int8)
import Data.List (intercalate)

-- a number as the model's ZV: ZvNat{n} is n, ZvNeg{n} is -(n+1)
zv :: Integral a => a -> String
zv x
  | n >= 0 = "C.ZvNat{" ++ show n ++ "n}"
  | otherwise = "C.ZvNeg{" ++ show (negate n - 1) ++ "n}"
  where
    n = toInteger x

-- an answer, an ArithException (divide by zero, overflow) its None
answer :: IO String -> IO String
answer v = do
  r <- try (v >>= evaluate . length')
  pure (either (\e -> const "None{}" (e :: ArithException)) (\s -> "Some{" ++ s ++ "}") r)
  where
    length' s = length s `seq` s

num :: Integral a => a -> IO String
num x = evaluate x >> pure (zv x)

bool :: Bool -> IO String
bool b = pure ("C.ZvBool{" ++ (if b then "True" else "False") ++ "{}}")

-- the model's primitives, at Int (or Int8): Haskell's own, and BendRt's
-- wrappers as prelude/Back/BendRt.hs defines them (b'Nat'sub a b =
-- if a < b then 0 else a - b, ...)
ops :: Integral a => [(String, a -> a -> IO String)]
ops =
  [ ("PAdd", \a b -> num (a + b))
  , ("PLt", \a b -> bool (a < b))
  , ("PSub", \a b -> num (a - b))
  , ("PDiv", \a b -> num (a `div` b))
  , ("PMod", \a b -> num (a `mod` b))
  , ("PSubT", \a b -> num (if a < b then 0 else a - b))
  , ("PDivT", \a b -> num (if b == 0 then 0 else a `div` b))
  , ("PModT", \a b -> num (if b == 0 then a else a `mod` b))
  ]

grid :: [(Int, Int)]
grid = [(a, b) | a <- [-4 .. 4], b <- [-4 .. 4]]

grid8 :: [(Int8, Int8)]
grid8 = [(a, b) | a <- edge, b <- edge]
  where
    edge = [minBound, minBound + 1, -64, -2, -1, 0, 1, 2, 64, maxBound - 1, maxBound]

-- a table: its grid's name, the model's call, the ops' defs' prefix
table :: Integral a => String -> String -> String -> [(a, a)] -> IO ()
table g t prefix pairs = do
  putStrLn ""
  putStrLn ("def " ++ g ++ "() -> List<&2, C.ZV>:")
  putStrLn ("  [" ++ intercalate ", " ["C.ZvPair{" ++ zv a ++ ", " ++ zv b ++ "}" | (a, b) <- pairs] ++ "]")
  mapM_ op ops
  where
    op (name, f) = do
      rs <- mapM (\(a, b) -> answer (f a b)) pairs
      putStrLn ""
      putStrLn ("def " ++ prefix ++ "." ++ name ++ "() -> {" ++ t ++ "(C." ++ name ++ "{}, " ++ g ++ "()) == [" ++ intercalate ", " rs ++ "] : List<&2, Maybe<&2, C.ZV>>}:")
      putStrLn "  {==}"

main :: IO ()
main = do
  putStrLn "# generated by adj/IntGhc.hs (adj/int.zsh) from GHC's Int and Int8; do not edit"
  putStrLn "# Each ghc def: the model's Int primitive (Core.bend's z.prim) at every"
  putStrLn "# pair of the grid -4..4 squared is GHC's Int's answer there; each ghc8"
  putStrLn "# def: the model's Int of range 127 (z.primw at RgInt{127n}) at every"
  putStrLn "# pair of Int8's edges is GHC's Int8's answer (None: divide by zero, or"
  putStrLn "# overflow, minBound `div` (-1))."
  putStrLn ""
  putStrLn "import Base"
  putStrLn "import ./Core.bend as C"
  putStrLn ""
  putStrLn "def tbl(+p: C.Prim, g: List<&2, C.ZV>) -> List<&2, Maybe<&2, C.ZV>>:"
  putStrLn "  match g:"
  putStrLn "    case Nil{}:"
  putStrLn "      Nil{}"
  putStrLn "    case v <> rest:"
  putStrLn "      C.z.prim(p, v) <> tbl(p, rest)"
  putStrLn ""
  putStrLn "def tbl8(+p: C.Prim, g: List<&2, C.ZV>) -> List<&2, Maybe<&2, C.ZV>>:"
  putStrLn "  match g:"
  putStrLn "    case Nil{}:"
  putStrLn "      Nil{}"
  putStrLn "    case v <> rest:"
  putStrLn "      C.z.primw(p, v, C.RgInt{C.int8.max()}) <> tbl8(p, rest)"
  table "grid" "tbl" "ghc" grid
  table "grid8" "tbl8" "ghc8" grid8
