-- adj/IntGhc.hs: GHC's own Int arithmetic on a grid (-4..4 squared),
-- written as Bend equations (adj/INT.bend) that Bend's checker and
-- BendTT's kernel compute against Core.bend's model of Int (z.prim): so
-- the model's Int is GHC's, not one written to fit the proof.  Run by
-- adj/int.zsh; INT.bend is its output, not edited by hand.
module Main (main) where

import Control.Exception (ArithException, evaluate, try)
import Data.List (intercalate)

-- an Int as the model's ZV: ZvNat{n} is n, ZvNeg{n} is -(n+1)
zv :: Int -> String
zv n
  | n >= 0 = "C.ZvNat{" ++ show n ++ "n}"
  | otherwise = "C.ZvNeg{" ++ show (negate n - 1) ++ "n}"

-- an answer, an ArithException (divide by zero) its None
answer :: IO String -> IO String
answer v = do
  r <- try (v >>= evaluate . length' )
  pure (either (\e -> const "None{}" (e :: ArithException)) (\s -> "Some{" ++ s ++ "}") r)
  where
    length' s = length s `seq` s

num :: Int -> IO String
num x = evaluate x >> pure (zv x)

bool :: Bool -> IO String
bool b = pure ("C.ZvBool{" ++ (if b then "True" else "False") ++ "{}}")

-- the model's primitives, at Int: Haskell's own, and BendRt's wrappers as
-- prelude/Back/BendRt.hs defines them (b'Nat'sub a b = max 0 (a - b), ...)
ops :: [(String, Int -> Int -> IO String)]
ops =
  [ ("PAdd", \a b -> num (a + b))
  , ("PLt", \a b -> bool (a < b))
  , ("PSub", \a b -> num (a - b))
  , ("PDiv", \a b -> num (a `div` b))
  , ("PMod", \a b -> num (a `mod` b))
  , ("PSubT", \a b -> num (max 0 (a - b)))
  , ("PDivT", \a b -> num (if b == 0 then 0 else a `div` b))
  , ("PModT", \a b -> num (if b == 0 then a else a `mod` b))
  ]

grid :: [(Int, Int)]
grid = [(a, b) | a <- [-4 .. 4], b <- [-4 .. 4]]

main :: IO ()
main = do
  putStrLn "# generated by adj/IntGhc.hs (adj/int.zsh) from GHC's Int; do not edit"
  putStrLn "# Each def: the model's Int primitive (Core.bend's z.prim) at every pair"
  putStrLn "# of the grid -4..4 squared is GHC's answer there (None: divide by zero)."
  putStrLn ""
  putStrLn "import Base"
  putStrLn "import ./Core.bend as C"
  putStrLn ""
  putStrLn "def grid() -> List<&2, C.ZV>:"
  putStrLn ("  [" ++ intercalate ", " ["C.ZvPair{" ++ zv a ++ ", " ++ zv b ++ "}" | (a, b) <- grid] ++ "]")
  putStrLn ""
  putStrLn "def tbl(+p: C.Prim, g: List<&2, C.ZV>) -> List<&2, Maybe<&2, C.ZV>>:"
  putStrLn "  match g:"
  putStrLn "    case Nil{}:"
  putStrLn "      Nil{}"
  putStrLn "    case v <> rest:"
  putStrLn "      C.z.prim(p, v) <> tbl(p, rest)"
  mapM_ op ops
  where
    op (name, f) = do
      rs <- mapM (\(a, b) -> answer (f a b)) grid
      putStrLn ""
      putStrLn ("def ghc." ++ name ++ "() -> {tbl(C." ++ name ++ "{}, grid()) == [" ++ intercalate ", " rs ++ "] : List<&2, Maybe<&2, C.ZV>>}:")
      putStrLn "  {==}"
